// Bundles prompts/*.md into lib/prompts.generated.ts so prompt text is compiled
// into the server build (it can't go missing on Vercel). Runs before dev/build.
// Fails the build if prompts/config.json points at a version that doesn't exist.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "prompts";
const config = JSON.parse(readFileSync(join(dir, "config.json"), "utf8"));

const prompts = {};
for (const file of readdirSync(dir)) {
  const m = file.match(/^([a-z]+)_(v\d+)\.md$/);
  if (!m) continue;
  prompts[`${m[1]}_${m[2]}`] = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n");
}

for (const [feature, version] of Object.entries(config)) {
  if (!prompts[`${feature}_${version}`]) {
    console.error(`prompts/config.json: "${feature}": "${version}" but prompts/${feature}_${version}.md does not exist`);
    process.exit(1);
  }
}

const out =
  "// AUTO-GENERATED by scripts/build-prompts.mjs from prompts/*.md. Do not edit.\n" +
  `export const PROMPTS: Record<string, string> = ${JSON.stringify(prompts, null, 2)};\n`;
writeFileSync(join("lib", "prompts.generated.ts"), out);
console.log(`prompts: bundled ${Object.keys(prompts).join(", ")}`);
